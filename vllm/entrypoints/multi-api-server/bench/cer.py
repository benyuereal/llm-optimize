# 字错率 (按字符算, 含标点)
total_chars = 0
total_edits = 0
print(f"{'#':<3}{'编辑距离':>8}{'原始字数':>8}{'CER':>8}")
print("-"*30)
for i, (a, b) in enumerate(pairs):
    d = editdistance.eval(a, b)
    cer = d / len(a) if a else 0
    total_chars += len(a)
    total_edits += d
    print(f"{i:<3}{d:>8}{len(a):>8}{cer*100:>7.1f}%")

overall_cer = total_edits / total_chars
print("-"*30)
print(f"整体字错率 (含标点): {overall_cer*100:.2f}%")

# 去标点后的纯汉字字错率 (业务更关心这个)
import re
def strip_punct(s):
    return re.sub(r'[，。？、！；：""''…—\-—\s,.\?!:;]', '', s)

total_chars_np = 0
total_edits_np = 0
for a, b in pairs:
    an, bn = strip_punct(a), strip_punct(b)
    total_chars_np += len(an)
    total_edits_np += editdistance.eval(an, bn)
print(f"纯汉字字错率 (去标点): {total_edits_np/total_chars_np*100:.2f}%")
print(f"  其中原始汉字总数: {total_chars_np}, 编辑距离总和: {total_edits_np}")
